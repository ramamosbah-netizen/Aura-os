import { randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const secretDir = join(repoRoot, '.aura-storage', 'secrets');
const apiEnvPath = join(repoRoot, 'apps', 'api', '.env.local');
const webEnvPath = join(repoRoot, 'apps', 'web', '.env.local');
const jwtPath = join(secretDir, 'local-auth-jwt');
const passwordPath = join(secretDir, 'master-admin-password');

async function ensureSecret(path, bytes) {
  try {
    const current = (await readFile(path, 'utf8')).trim();
    if (current) return false;
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  await writeFile(path, `${randomBytes(bytes).toString('base64url')}\n`, { encoding: 'utf8', mode: 0o600 });
  return true;
}

async function upsertEnv(path, values) {
  let source = '';
  try {
    source = await readFile(path, 'utf8');
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  const keys = new Set(Object.keys(values));
  const kept = source
    .split(/\r?\n/)
    .filter((line) => {
      const match = line.match(/^\s*([A-Z0-9_]+)\s*=/);
      return !match || !keys.has(match[1]);
    });
  while (kept.at(-1) === '') kept.pop();
  const next = [
    ...kept,
    '',
    '# Local authentication (generated by scripts/configure-local-auth.mjs; gitignored).',
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n');
  await writeFile(path, next, 'utf8');
}

await mkdir(secretDir, { recursive: true, mode: 0o700 });
const generatedJwt = await ensureSecret(jwtPath, 48);
const generatedPassword = await ensureSecret(passwordPath, 24);
const portable = (path) => path.replaceAll('\\', '/');

await upsertEnv(apiEnvPath, {
  AUTH_JWT_SECRET_FILE: portable(jwtPath),
  AUTH_DEV_PASSWORD_FILE: portable(passwordPath),
  AUTH_REQUIRED: 'true',
  AUTH_DEFAULT_TENANT: 'dev-tenant',
  AUTH_MASTER_ADMIN_USER: 'u-admin',
  AUTH_MASTER_ADMIN_TENANT: 'dev-tenant',
  AUTH_LOCAL_LOGIN_USERS: 'u-admin',
  AUTH_SESSION_TTL_SECONDS: '28800',
  AUTH_ALLOW_DEV_TOKENS: 'false',
  CORS_ALLOWED_ORIGINS: 'http://localhost:3000',
});
await upsertEnv(webEnvPath, {
  AURA_API_URL: 'http://localhost:4000',
  WEB_AUTH_REQUIRED: 'true',
});

console.log('Local master-admin authentication configured.');
console.log(`User: u-admin`);
console.log(`Password file: ${relative(repoRoot, passwordPath)}`);
console.log(`JWT secret: ${generatedJwt ? 'generated' : 'preserved'}; password: ${generatedPassword ? 'generated' : 'preserved'}.`);
